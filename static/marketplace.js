function csrfToken() {
  return document.querySelector('meta[name="csrf-token"]')?.content || "";
}

document.querySelectorAll("[data-product-draft]").forEach((button) => {
  button.addEventListener("click", async () => {
    const form = button.closest("form");
    const message = document.querySelector(button.dataset.messageTarget);
    const values = Object.fromEntries(new FormData(form).entries());
    const fields = Object.fromEntries(
      ["item_name", "category", "material", "condition", "dimensions", "price", "colour", "additional_details"]
        .map((key) => [key, values[key] || ""]),
    );
    if (!fields.item_name || !fields.category) {
      message.textContent = "Enter an item name and furniture category first.";
      return;
    }
    button.disabled = true;
    message.textContent = "Asking local Ollama for a factual draft…";
    try {
      const response = await fetch("/api/generate", {
        method: "POST",
        headers: { "Content-Type": "application/json", "X-CSRFToken": csrfToken() },
        body: JSON.stringify({ task: "product", fields }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "The draft could not be prepared.");
      form.elements.description.value = data.result;
      message.textContent = data.source === "local_ai"
        ? "Local AI draft added to the description field. Review it before saving."
        : "Safe facts-only fallback added (not AI-generated). Review it before saving.";
    } catch (error) {
      message.textContent = error.message;
    } finally {
      button.disabled = false;
    }
  });
});

document.querySelectorAll("[data-reply-draft]").forEach((form) => {
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const button = form.querySelector("button[type=submit]");
    const message = document.querySelector("#reply-draft-message");
    const source = document.querySelector("#reply-draft-source");
    const fields = Object.fromEntries(new FormData(form).entries());
    button.disabled = true;
    message.textContent = "Preparing a draft on local Ollama…";
    source.textContent = "";
    try {
      const response = await fetch(form.dataset.endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json", "X-CSRFToken": csrfToken() },
        body: JSON.stringify({ policies: fields }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "A draft could not be prepared.");
      document.querySelector("#body").value = data.result;
      source.textContent = data.source === "local_ai" ? "Generated by local Ollama AI" : "Safe deterministic fallback — not AI-generated";
      message.textContent = `${data.notice} The text remains in the message box until you press Send message.`;
    } catch (error) {
      message.textContent = error.message;
    } finally {
      button.disabled = false;
    }
  });
});
