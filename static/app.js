const form = document.querySelector("#product-form");
const message = document.querySelector("#form-message");
const result = document.querySelector("#result");
const resultSource = document.querySelector("#result-source");
const generateButton = document.querySelector("#generate-button");
const copyButton = document.querySelector("#copy-button");
const copyMessage = document.querySelector("#copy-message");
const aiStatus = document.querySelector("#ai-status");

async function refreshAIStatus() {
  try {
    const response = await fetch("/api/status");
    const data = await response.json();
    aiStatus.textContent = data.message;
    aiStatus.dataset.ready = data.ready;
  } catch {
    aiStatus.textContent = "Could not check local AI. Start the app again and retry.";
    aiStatus.dataset.ready = "false";
  }
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  message.textContent = "";
  copyMessage.textContent = "";

  if (!form.reportValidity()) {
    message.textContent = "Add the item name and furniture category before generating.";
    return;
  }

  const fields = Object.fromEntries(new FormData(form).entries());
  resultSource.textContent = "";
  result.textContent = "Generating a new description locally…";
  copyButton.disabled = true;
  generateButton.disabled = true;
  generateButton.textContent = "Generating locally…";
  message.textContent = "This may take a little while on this computer.";

  try {
    const response = await fetch("/api/generate", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "X-CSRFToken": document.querySelector('meta[name="csrf-token"]').content,
      },
      body: JSON.stringify({ task: "product", fields }),
    });
    let data;
    try {
      data = await response.json();
    } catch {
      throw new Error("The app could not read the response. Your details are still in the form; please try again.");
    }
    if (!response.ok) throw new Error(data.error || "Generation failed. Please try again.");
    result.textContent = data.result;
    resultSource.textContent = data.source === "local_ai"
      ? "Generated by local Ollama AI."
      : "Safe facts-only fallback — not AI-generated.";
    copyButton.disabled = false;
    message.textContent = data.notice || "Review the description before using it.";
  } catch (error) {
    result.textContent = "No new description was generated.";
    resultSource.textContent = "";
    message.textContent = error.message;
  } finally {
    generateButton.disabled = false;
    generateButton.textContent = "Generate description";
  }
});

copyButton.addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText(result.textContent);
    copyMessage.textContent = "Copied to clipboard.";
  } catch {
    copyMessage.textContent = "Copy was blocked. Select the text above and copy it manually.";
  }
});

refreshAIStatus();
